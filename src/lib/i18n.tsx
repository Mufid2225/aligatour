"use client";

import { createContext, useContext, useState, useCallback, useEffect, type ReactNode } from "react";

type Lang = "id" | "en";

interface Ctx { lang: Lang; toggle: () => void }

const LanguageContext = createContext<Ctx>({ lang: "id", toggle: () => {} });

const STORAGE_KEY = "aligatour-lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    if (typeof window !== "undefined") {
      const saved = sessionStorage.getItem(STORAGE_KEY);
      if (saved === "id" || saved === "en") return saved;
    }
    return "id";
  });

  const toggle = useCallback(() => {
    setLang((p) => {
      const next = p === "id" ? "en" : "id";
      sessionStorage.setItem(STORAGE_KEY, next);
      return next;
    });
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  return <LanguageContext.Provider value={{ lang, toggle }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

